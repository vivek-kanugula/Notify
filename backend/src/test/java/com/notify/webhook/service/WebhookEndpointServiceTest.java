package com.notify.webhook.service;

import com.notify.AbstractPostgresIntegrationTest;
import com.notify.common.error.ErrorCode;
import com.notify.common.error.NotifyException;
import com.notify.tenant.entity.TenantEntity;
import com.notify.tenant.repository.TenantRepository;
import com.notify.webhook.model.WebhookDestination;
import com.notify.webhook.model.WebhookEndpointView;
import com.notify.webhook.model.WebhookUpsertResult;
import com.notify.webhook.security.DestinationRejectedException;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.TestPropertySource;

import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * , , and against a real database. The secret is the asset here: it is generated by the
 * server, shown once, stored only encrypted, and never returned by a read.
 */
@TestPropertySource(properties = {
        // A demo URL makes the is_demo derivation testable; the allowlist is what lets that one host use plain http.
        "notify.demo.webhook-url=http://localhost:9099/demo/webhook",
        "notify.webhook.demo-allowlist=localhost,127.0.0.1"
})
class WebhookEndpointServiceTest extends AbstractPostgresIntegrationTest {

    private static final String DEMO_URL = "http://localhost:9099/demo/webhook";

    @Autowired
    private WebhookEndpointService service;

    @Autowired
    private WebhookSecretCipher cipher;

    @Autowired
    private TenantRepository tenantRepository;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    private UUID newTenant() {
        String slug = "wh-" + UUID.randomUUID().toString().substring(0, 8);
        return tenantRepository.saveAndFlush(new TenantEntity("Webhook Tenant", slug)).getId();
    }

    private String storedCiphertext(UUID tenantId) {
        return jdbcTemplate.queryForObject(
                "SELECT signing_secret_enc FROM webhook_endpoints WHERE tenant_id = ?", String.class, tenantId);
    }

    @Test
    @DisplayName("an unconfigured tenant has no endpoint, so the API can answer 404 rather than inventing one")
    void findIsEmptyWhenUnconfigured() {
        assertThat(service.find(newTenant())).isEmpty();
    }

    @Test
    @DisplayName("the first upsert creates the endpoint and returns the secret exactly once")
    void firstUpsertCreatesAndReturnsSecretOnce() {
        UUID tenantId = newTenant();

        WebhookUpsertResult created = service.upsert(tenantId, "https://receiver.example.com/hook", null);

        assertThat(created.created()).isTrue();
        assertThat(created.secretOnce()).startsWith("whsec_");
        assertThat(created.view().url()).isEqualTo("https://receiver.example.com/hook");
        assertThat(created.view().enabled()).isTrue();
        assertThat(created.view().demo()).isFalse();

        WebhookUpsertResult updated = service.upsert(tenantId, "https://other.example.com/hook", null);
        assertThat(updated.created()).isFalse();
        assertThat(updated.secretOnce()).as("an update must not re-present the secret").isNull();
    }

    @Test
    @DisplayName("a read never returns the signing secret in any form")
    void readNeverReturnsTheSecret() {
        UUID tenantId = newTenant();
        String secret = service.upsert(tenantId, "https://receiver.example.com/hook", null).secretOnce();

        Optional<WebhookEndpointView> view = service.find(tenantId);

        assertThat(view).isPresent();
        assertThat(view.get().toString()).doesNotContain(secret);
        assertThat(view.get().toString()).doesNotContain("whsec_");
    }

    @Test
    @DisplayName("the stored column holds ciphertext, not the secret, and decrypts back to it")
    void secretIsEncryptedAtRest() {
        UUID tenantId = newTenant();
        String secret = service.upsert(tenantId, "https://receiver.example.com/hook", null).secretOnce();

        String stored = storedCiphertext(tenantId);

        assertThat(stored).isNotNull().isNotEqualTo(secret).doesNotContain(secret).doesNotContain("whsec_");
        assertThat(cipher.decrypt(tenantId, stored)).isEqualTo(secret);
    }

    @Test
    @DisplayName("the stored ciphertext is bound to its tenant, so a row moved between tenants cannot be decrypted")
    void ciphertextIsBoundToTheTenant() {
        UUID tenantId = newTenant();
        UUID otherTenant = newTenant();
        service.upsert(tenantId, "https://receiver.example.com/hook", null);

        String stored = storedCiphertext(tenantId);

        assertThatThrownBy(() -> cipher.decrypt(otherTenant, stored)).isInstanceOf(Exception.class);
    }

    @Test
    @DisplayName("two endpoints never share a secret or a ciphertext, even for the same URL")
    void secretsAreDistinct() {
        UUID first = newTenant();
        UUID second = newTenant();

        String firstSecret = service.upsert(first, "https://receiver.example.com/hook", null).secretOnce();
        String secondSecret = service.upsert(second, "https://receiver.example.com/hook", null).secretOnce();

        assertThat(firstSecret).isNotEqualTo(secondSecret);
        assertThat(storedCiphertext(first)).isNotEqualTo(storedCiphertext(second));
    }

    @Test
    @DisplayName("rotation issues a new secret immediately and leaves the old one unusable")
    void rotationReplacesTheSecret() {
        UUID tenantId = newTenant();
        String original = service.upsert(tenantId, "https://receiver.example.com/hook", null).secretOnce();

        String rotated = service.rotateSecret(tenantId);

        assertThat(rotated).startsWith("whsec_").isNotEqualTo(original);
        assertThat(service.resolveDestination(tenantId)).get()
                .extracting(WebhookDestination::secret).isEqualTo(rotated);
    }

    @Test
    @DisplayName("rotating without an endpoint is NOT_FOUND rather than creating one silently")
    void rotationRequiresAnEndpoint() {
        assertThatThrownBy(() -> service.rotateSecret(newTenant()))
                .isInstanceOf(NotifyException.class)
                .extracting(e -> ((NotifyException) e).getErrorCode())
                .isEqualTo(ErrorCode.NOT_FOUND);
    }

    @Test
    @DisplayName("resolveDestination returns the tenant's current URL and plaintext secret for the sender")
    void resolveDestinationDecrypts() {
        UUID tenantId = newTenant();
        String secret = service.upsert(tenantId, "https://receiver.example.com/hook", null).secretOnce();

        WebhookDestination destination = service.resolveDestination(tenantId).orElseThrow();

        assertThat(destination.tenantId()).isEqualTo(tenantId);
        assertThat(destination.url()).isEqualTo("https://receiver.example.com/hook");
        assertThat(destination.secret()).isEqualTo(secret);
        assertThat(destination.enabled()).isTrue();
        assertThat(destination.demo()).isFalse();
        assertThat(destination.toString()).doesNotContain(secret);
    }

    @Test
    @DisplayName("a corrected URL is picked up by the next attempt, because the destination is read per attempt")
    void destinationFollowsTheCurrentConfiguration() {
        UUID tenantId = newTenant();
        service.upsert(tenantId, "https://first.example.com/hook", null);
        service.upsert(tenantId, "https://second.example.com/hook", null);

        assertThat(service.resolveDestination(tenantId).orElseThrow().url())
                .isEqualTo("https://second.example.com/hook");
    }

    @Test
    @DisplayName("disabling keeps the row and the secret, so re-enabling does not force a receiver to be reconfigured")
    void disablingIsReversible() {
        UUID tenantId = newTenant();
        String secret = service.upsert(tenantId, "https://receiver.example.com/hook", null).secretOnce();

        service.upsert(tenantId, "https://receiver.example.com/hook", false);
        assertThat(service.resolveDestination(tenantId).orElseThrow().enabled()).isFalse();

        service.upsert(tenantId, "https://receiver.example.com/hook", true);
        WebhookDestination reEnabled = service.resolveDestination(tenantId).orElseThrow();
        assertThat(reEnabled.enabled()).isTrue();
        assertThat(reEnabled.secret()).isEqualTo(secret);
    }

    @Test
    @DisplayName("a rejected URL is never stored: a blocked destination cannot be smuggled in by configuring it")
    void rejectedUrlIsNotStored() {
        UUID tenantId = newTenant();

        assertThatThrownBy(() -> service.upsert(tenantId, "http://169.254.169.254/latest/meta-data/", null))
                .isInstanceOf(DestinationRejectedException.class);
        assertThatThrownBy(() -> service.upsert(tenantId, "https://10.0.0.5/hook", null))
                .isInstanceOf(DestinationRejectedException.class);
        assertThatThrownBy(() -> service.upsert(tenantId, "ftp://receiver.example.com/hook", null))
                .isInstanceOf(DestinationRejectedException.class);

        assertThat(service.find(tenantId)).isEmpty();
    }

    @Test
    @DisplayName("is_demo is derived from the configured demo URL, so a tenant cannot flag its own endpoint")
    void demoFlagIsDerivedNotRequested() {
        UUID tenantId = newTenant();

        WebhookUpsertResult demo = service.upsert(tenantId, DEMO_URL, null);
        assertThat(demo.view().demo()).isTrue();

        WebhookUpsertResult ownUrl = service.upsert(tenantId, "https://receiver.example.com/hook", null);
        assertThat(ownUrl.view().demo()).as("moving away from the demo URL clears the flag").isFalse();
    }

    @Test
    @DisplayName("a tenant cannot use plain http for its own host even though the demo host may")
    void demoExceptionIsHostSpecific() {
        UUID tenantId = newTenant();

        assertThatThrownBy(() -> service.upsert(tenantId, "http://receiver.example.com/hook", null))
                .isInstanceOf(DestinationRejectedException.class);
        assertThatThrownBy(() -> service.upsert(tenantId, "http://localhost:9099/other", null))
                .as("a non-demo path on the demo host is not the demo endpoint")
                .isInstanceOf(DestinationRejectedException.class);
    }

    @Test
    @DisplayName("provisionDefault creates one demo endpoint and is idempotent, so signup can call it safely")
    void provisionDefaultIsIdempotent() {
        UUID tenantId = newTenant();

        service.provisionDefault(tenantId);
        WebhookEndpointView first = service.find(tenantId).orElseThrow();
        service.provisionDefault(tenantId);
        WebhookEndpointView second = service.find(tenantId).orElseThrow();

        assertThat(first.url()).isEqualTo(DEMO_URL);
        assertThat(first.demo()).isTrue();
        assertThat(first.enabled()).isTrue();
        assertThat(second.id()).isEqualTo(first.id());
        assertThat(second.updatedAt()).isEqualTo(first.updatedAt());
    }

    @Test
    @DisplayName("provisionDefault never overwrites an endpoint the tenant already configured")
    void provisionDefaultDoesNotOverwrite() {
        UUID tenantId = newTenant();
        service.upsert(tenantId, "https://receiver.example.com/hook", null);

        service.provisionDefault(tenantId);

        assertThat(service.find(tenantId).orElseThrow().url()).isEqualTo("https://receiver.example.com/hook");
    }

    @Test
    @DisplayName("a provisioned endpoint has a usable signing secret, stored encrypted like any other")
    void provisionedEndpointIsUsable() {
        UUID tenantId = newTenant();
        service.provisionDefault(tenantId);

        WebhookDestination destination = service.resolveDestination(tenantId).orElseThrow();

        assertThat(destination.secret()).startsWith("whsec_");
        assertThat(storedCiphertext(tenantId)).doesNotContain(destination.secret());
    }
}
